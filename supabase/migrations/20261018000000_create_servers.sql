CREATE TABLE server_question_sets (
    username_key TEXT NOT NULL,
    server_id BIGINT NOT NULL,
    question_set_id BIGINT NOT NULL,
    PRIMARY KEY (username_key, server_id, question_set_id),
    FOREIGN KEY (username_key, server_id)
        REFERENCES servers(username_key, id) ON DELETE CASCADE,
    FOREIGN KEY (username_key, question_set_id)
        REFERENCES question_sets(username_key, id) ON DELETE CASCADE
);

INSERT INTO server_question_sets (username_key, server_id, question_set_id)
SELECT players.username_key, servers.id, players.active_question_set
FROM players
JOIN servers
    ON servers.username_key = players.username_key
    AND servers.is_default
WHERE players.active_question_set IS NOT NULL;

