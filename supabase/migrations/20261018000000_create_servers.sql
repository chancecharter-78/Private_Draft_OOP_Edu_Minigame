CREATE TABLE servers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username_key TEXT NOT NULL REFERENCES players(username_key) ON DELETE CASCADE,
    name TEXT NOT NULL,
    is_default BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (username_key, id)
);

CREATE UNIQUE INDEX servers_owner_name_case_insensitive
    ON servers (username_key, lower(name));

ALTER TABLE question_sets
    ADD CONSTRAINT question_sets_owner_id_unique
    UNIQUE (username_key, id);

