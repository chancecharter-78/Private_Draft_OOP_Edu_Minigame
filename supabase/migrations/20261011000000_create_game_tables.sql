CREATE TABLE players (
    username_key TEXT PRIMARY KEY,
    username TEXT NOT NULL,
    password_salt TEXT NOT NULL DEFAULT '',
    password_hash TEXT NOT NULL DEFAULT '',
    score INTEGER NOT NULL DEFAULT 0,
    level INTEGER NOT NULL DEFAULT 1,
    completed_rounds INTEGER NOT NULL DEFAULT 0,
    active_question_set BIGINT
);

CREATE TABLE question_sets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username_key TEXT NOT NULL REFERENCES players(username_key) ON DELETE CASCADE,
    name TEXT NOT NULL,
    csv_text TEXT NOT NULL,
    UNIQUE (username_key, name)
);

CREATE UNIQUE INDEX question_sets_owner_name_case_insensitive
    ON question_sets (username_key, lower(name));

CREATE TABLE player_clears (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username_key TEXT NOT NULL REFERENCES players(username_key) ON DELETE CASCADE,
    game TEXT NOT NULL,
    level INTEGER NOT NULL,
    points INTEGER NOT NULL,
    details TEXT NOT NULL
);

CREATE INDEX players_leaderboard_order
    ON players (score DESC, completed_rounds DESC);

CREATE INDEX player_clears_player_id
    ON player_clears (username_key, id);
